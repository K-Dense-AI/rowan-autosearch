@click.group()
def cli() -> None:
    """Manage Rowan autosearch run state."""


@cli.command()
@click.option("--run", "run_id", required=True, help="Short run identifier (slug).")
@click.option("--objective", required=True, help="Plain-English objective statement.")
@click.option("--direction", type=click.Choice(["maximize", "minimize"]), required=True)
@click.option("--metric", "primary_metric", required=True,
              help="Name of the primary metric this objective optimizes (e.g. logS, pKa, redox_potential).")
@click.option("--workflow", "workflow_type", required=True,
              help="Rowan workflow_type, e.g. solubility, pka, redox_potential, admet.")
@click.option("--start-smiles", required=True, help="Starting molecule SMILES.")
@click.option("--metric-path", default=None,
              help="Dot-path into object_data to find the metric value, e.g. 'solubility.logS_25C'. "
                   "If omitted, score.py will try common keys for the workflow.")
@click.option("--constraint", "constraints", multiple=True,
              help="Constraint as key=value, repeatable. e.g. mw_max=350 logp_max=4")
@click.option("--workflow-param", "workflow_params", multiple=True,
              help="Rowan workflow argument as key=json_value, repeatable. "
                   "Examples: method=\"fastsolv\", solvents='[\"water\"]', protein=\"uuid\".")
@click.option("--objective-term", "objective_terms", multiple=True,
              help="Composite objective term as JSON object, repeatable. "
                   "Example: '{\"name\":\"mw\",\"source\":\"local\",\"metric\":\"mw\",\"goal\":\"minimize\",\"weight\":0.01}'")
@click.option("--max-iter", default=50, type=int)
@click.option("--candidates-per-iter", default=4, type=int)
@click.option("--force", is_flag=True, help="Overwrite existing config.")
def init(run_id, objective, direction, primary_metric, workflow_type, start_smiles,
         metric_path, constraints, workflow_params, objective_terms, max_iter,
         candidates_per_iter, force):
    """Initialize a new run."""
    p = run_dir(run_id) / "config.json"
    if p.exists() and not force:
        raise click.ClickException(f"{p} exists. Use --force to overwrite.")

    constraint_dict = parse_key_value_options(constraints, "--constraint")
    workflow_param_dict = parse_key_value_options(workflow_params, "--workflow-param")

    parsed_objective_terms = []
    for term in objective_terms:
        value = parse_jsonish(term)
        if not isinstance(value, dict):
            raise click.ClickException(
                f"Bad --objective-term {term!r}; expected a JSON object"
            )
        parsed_objective_terms.append(value)

    cfg = {
        "run_id": run_id,
        "objective": objective,
        "objective_direction": direction,
        "primary_metric": primary_metric,
        "workflow_type": workflow_type,
        "start_smiles": start_smiles,
        "metric_path": metric_path,
        "constraints": constraint_dict,
        "max_iterations": max_iter,
        "candidates_per_iter": candidates_per_iter,
        "created_at": now_iso(),
    }
    if workflow_param_dict:
        cfg["workflow_params"] = workflow_param_dict
    if parsed_objective_terms:
        cfg["optimization_objective"] = {
            "name": primary_metric,
            "terms": parsed_objective_terms,
        }
    save_config(run_id, cfg)
    (run_dir(run_id) / "iterations").mkdir(parents=True, exist_ok=True)
    (run_dir(run_id) / "plots").mkdir(parents=True, exist_ok=True)
    click.echo(f"Initialized run {run_id} at {run_dir(run_id)}")
    click.echo(json.dumps(cfg, indent=2))


@cli.command()
@click.option("--run", "run_id", required=True)
def status(run_id):
    """Print run summary: config, iteration count, best-so-far."""
    cfg = load_config(run_id)
    iters = list_iterations(run_id)
    best = best_so_far(run_id)
    click.echo(f"Run: {run_id}")
    click.echo(f"  Objective:     {cfg['objective']}")
    click.echo(f"  Direction:     {cfg['objective_direction']} {cfg['primary_metric']}")
    click.echo(f"  Workflow:      {cfg['workflow_type']}")
    click.echo(f"  Iterations:    {len(iters)} / {cfg['max_iterations']}")
    if best:
        metric_value = best.get("metrics", {}).get(cfg["primary_metric"], best["score"])
        click.echo(f"  Best so far:   {best['smiles']}  ({cfg['primary_metric']}={metric_value})")
        click.echo(f"  Found at iter: {best['iter']}")
    else:
        click.echo("  Best so far:   (none yet)")


@cli.command(name="list")
def list_runs():
    """List all runs."""
    if not RUNS_DIR.exists():
        click.echo("No runs yet.")
        return
    for d in sorted(RUNS_DIR.iterdir()):
        if (d / "config.json").exists():
            cfg = json.loads((d / "config.json").read_text())
            n = len(list_iterations(d.name))
            click.echo(f"  {d.name:30s}  iter={n:3d}  obj={cfg['objective'][:60]}")


if __name__ == "__main__":
    cli()
