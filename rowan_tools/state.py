"""Run state management.

Each run lives at runs/<run_id>/ with:
  config.json       — run-level config (objective, workflow, constraints)
  iterations/NNNN.json — one file per iteration with candidates + scores
  plots/, report.html — generated by viz.build_report
"""
from __future__ import annotations

import json
import os
import re
import tempfile
from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import click

ROOT = Path(__file__).resolve().parent.parent
RUNS_DIR = ROOT / "runs"


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def run_dir(run_id: str) -> Path:
    return RUNS_DIR / run_id


def iter_path(run_id: str, n: int) -> Path:
    return run_dir(run_id) / "iterations" / f"{n:04d}.json"


def load_config(run_id: str) -> dict[str, Any]:
    p = run_dir(run_id) / "config.json"
    if not p.exists():
        raise FileNotFoundError(f"No config at {p}. Run `rowan-state init` first.")
    return json.loads(p.read_text())


def _atomic_write_json(p: Path, data: dict[str, Any]) -> None:
    """Write JSON with an atomic replace so readers never see partial state."""
    p.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(
        dir=p.parent,
        prefix=f".{p.name}.",
        suffix=".tmp",
    )
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "w") as f:
            json.dump(data, f, indent=2)
            f.write("\n")
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, p)
    finally:
        tmp.unlink(missing_ok=True)


def save_config(run_id: str, cfg: dict[str, Any]) -> None:
    p = run_dir(run_id) / "config.json"
    _atomic_write_json(p, cfg)


def list_iterations(run_id: str) -> list[int]:
    d = run_dir(run_id) / "iterations"
    if not d.exists():
        return []
    nums = []
    for p in d.glob("*.json"):
        m = re.match(r"(\d+)\.json$", p.name)
        if m:
            nums.append(int(m.group(1)))
    return sorted(nums)


def load_iter(run_id: str, n: int) -> dict[str, Any]:
    return json.loads(iter_path(run_id, n).read_text())


def save_iter(run_id: str, n: int, data: dict[str, Any]) -> None:
    _atomic_write_json(iter_path(run_id, n), data)


def reserve_iter(run_id: str, data: dict[str, Any]) -> int:
    """Atomically reserve and create the next iteration number.

    Sidecar reservation files prevent concurrent score processes from choosing
    the same number. A process that dies while reserving may leave a harmless
    gap; iteration consumers already support non-contiguous numbering.
    """
    iterations_dir = run_dir(run_id) / "iterations"
    iterations_dir.mkdir(parents=True, exist_ok=True)
    existing = list_iterations(run_id)
    n = (max(existing) + 1) if existing else 1

    while True:
        reservation = iterations_dir / f".{n:04d}.reserve"
        try:
            fd = os.open(reservation, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
        except FileExistsError:
            n += 1
            continue

        os.close(fd)
        try:
            target = iter_path(run_id, n)
            if target.exists():
                n += 1
                continue
            record = dict(data)
            record["iter"] = n
            _atomic_write_json(target, record)
            return n
        finally:
            reservation.unlink(missing_ok=True)


def parse_jsonish(value: str) -> Any:
    """Parse CLI values as JSON when possible, falling back to strings."""
    try:
        return json.loads(value)
    except json.JSONDecodeError:
        pass
    try:
        return float(value)
    except ValueError:
        return value


def parse_key_value_options(values: tuple[str, ...], option_name: str) -> dict[str, Any]:
    parsed: dict[str, Any] = {}
    for item in values:
        if "=" not in item:
            raise click.ClickException(f"Bad {option_name} {item!r}; expected key=value")
        key, value = item.split("=", 1)
        parsed[key] = parse_jsonish(value)
    return parsed


def all_candidates(run_id: str) -> list[dict[str, Any]]:
    """Flat list of every scored candidate across all iterations."""
    out = []
    for n in list_iterations(run_id):
        it = load_iter(run_id, n)
        for c in it.get("candidates", []):
            c2 = dict(c)
            c2["iter"] = n
            out.append(c2)
    return out


def best_so_far(run_id: str) -> dict[str, Any] | None:
    cfg = load_config(run_id)
    direction = cfg.get("objective_direction", "maximize")
    cands = [c for c in all_candidates(run_id)
             if c.get("score") is not None and c.get("satisfies_constraints", True)]
    if not cands:
        return None
    return max(cands, key=lambda c: c["score"]) if direction == "maximize" \
        else min(cands, key=lambda c: c["score"])


